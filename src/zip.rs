//! ZIP reading and extraction (central directory based) — zero dependencies.
//! OWNER: runtime. API frozen by docs/CONTRACT.md.
//!
//! Only what a Minecraft launcher needs: locate the end-of-central-directory
//! record, parse the central directory (never the local headers' sizes, which
//! may be zero when a data descriptor is used), then extract stored (method 0)
//! and DEFLATE (method 8) entries.
//!
//! Safety rules applied while extracting:
//!   * entries whose path escapes the output directory (`..`, leading `/` or
//!     `\`, drive letter) are skipped, not written (a single odd entry in a
//!     third-party jar must not break a whole natives install);
//!   * `META-INF/` is skipped (jar metadata, never a native);
//!   * entries containing one of the caller's `excludes` fragments are skipped;
//!   * unsupported methods / encrypted entries are skipped with a message.
//!
//! Native jars keep their DLLs in sub-directories (`windows/x64/org/lwjgl/…`),
//! but the launcher passes `-Djava.library.path=<natives dir>`, so every
//! `.dll`/`.exe` found under a directory is *also* written flat into
//! `<out>/<basename>`. The nested copy is kept as well. Both count as files.

use crate::inflate;
use crate::util::{info, mkdirs, Res};
use std::collections::HashSet;
use std::fs::File;
use std::io::{Read, Seek, SeekFrom, Write};
use std::path::{Path, PathBuf};

const SIG_LOCAL: u32 = 0x0403_4B50;
const SIG_CENTRAL: u32 = 0x0201_4B50;
const SIG_EOCD: u32 = 0x0605_4B50;
const SIG_EOCD64: u32 = 0x0606_4B50;
const SIG_EOCD64_LOCATOR: u32 = 0x0706_4B50;

/// Extra field id carrying 64-bit sizes/offsets.
const EXTRA_ZIP64: u16 = 0x0001;

/// Maximum comment scan window (the EOCD record lives in the last 64 KiB).
const EOCD_WINDOW: u64 = 65_536 + 22;
/// Refuse absurd central directories (real ones are well under 1 MB).
const MAX_CD: u64 = 64 << 20;
/// Refuse to inflate a single entry larger than this (natives are tiny).
const MAX_ENTRY: u64 = 256 << 20;

// ---------------------------------------------------------------------------
// Low-level file access
// ---------------------------------------------------------------------------

struct Reader {
    file: File,
    size: u64,
    path: PathBuf,
}

impl Reader {
    fn open(path: &Path) -> Res<Reader> {
        let file = File::open(path)
            .map_err(|e| format!("cannot open zip {}: {e}", path.display()))?;
        let size = file
            .metadata()
            .map_err(|e| format!("cannot stat zip {}: {e}", path.display()))?
            .len();
        Ok(Reader { file, size, path: path.to_path_buf() })
    }

    fn read_at(&mut self, off: u64, len: usize) -> Res<Vec<u8>> {
        if off > self.size || off + len as u64 > self.size {
            return Err(format!(
                "zip {}: read of {len} bytes at {off} is past end of file ({} bytes)",
                self.path.display(),
                self.size
            ));
        }
        self.file
            .seek(SeekFrom::Start(off))
            .map_err(|e| format!("zip {}: seek failed: {e}", self.path.display()))?;
        let mut buf = vec![0u8; len];
        self.file
            .read_exact(&mut buf)
            .map_err(|e| format!("zip {}: read failed: {e}", self.path.display()))?;
        Ok(buf)
    }

    fn read_into(&mut self, off: u64, buf: &mut [u8]) -> Res<()> {
        if off > self.size || off + buf.len() as u64 > self.size {
            return Err(format!(
                "zip {}: read of {} bytes at {off} is past end of file ({} bytes)",
                self.path.display(),
                buf.len(),
                self.size
            ));
        }
        self.file
            .seek(SeekFrom::Start(off))
            .map_err(|e| format!("zip {}: seek failed: {e}", self.path.display()))?;
        self.file
            .read_exact(buf)
            .map_err(|e| format!("zip {}: read failed: {e}", self.path.display()))
    }
}

fn u16_at(b: &[u8], o: usize) -> u16 {
    u16::from_le_bytes([b[o], b[o + 1]])
}

fn u32_at(b: &[u8], o: usize) -> u32 {
    u32::from_le_bytes([b[o], b[o + 1], b[o + 2], b[o + 3]])
}

fn u64_at(b: &[u8], o: usize) -> u64 {
    let mut a = [0u8; 8];
    a.copy_from_slice(&b[o..o + 8]);
    u64::from_le_bytes(a)
}

// ---------------------------------------------------------------------------
// End of central directory
// ---------------------------------------------------------------------------

struct Eocd {
    entries: u64,
    cd_off: u64,
    cd_size: u64,
}

fn find_eocd(r: &mut Reader) -> Res<Eocd> {
    if r.size < 22 {
        return Err(format!(
            "zip {}: too small to be a zip archive ({} bytes)",
            r.path.display(),
            r.size
        ));
    }
    let tail_len = r.size.min(EOCD_WINDOW) as usize;
    let tail_off = r.size - tail_len as u64;
    let tail = r.read_at(tail_off, tail_len)?;

    // Scan backwards for the last EOCD signature whose comment length fits.
    let mut found: Option<usize> = None;
    let mut i = tail.len().saturating_sub(22);
    loop {
        if u32_at(&tail, i) == SIG_EOCD {
            let comment = u16_at(&tail, i + 20) as usize;
            if i + 22 + comment <= tail.len() {
                found = Some(i);
                break;
            }
        }
        if i == 0 {
            break;
        }
        i -= 1;
    }
    let pos = found.ok_or_else(|| {
        format!(
            "zip {}: end-of-central-directory record not found in the last {} bytes",
            r.path.display(),
            tail_len
        )
    })?;
    let eocd_file_off = tail_off + pos as u64;

    let mut entries = u16_at(&tail, pos + 10) as u64;
    let mut cd_size = u32_at(&tail, pos + 12) as u64;
    let mut cd_off = u32_at(&tail, pos + 16) as u64;

    if entries == 0xFFFF || cd_size == 0xFFFF_FFFF || cd_off == 0xFFFF_FFFF {
        // Look for the ZIP64 locator just before the classic EOCD record.
        if eocd_file_off < 20 {
            return Err(format!(
                "zip {}: classic EOCD reports ZIP64 sizes but no ZIP64 locator precedes it",
                r.path.display()
            ));
        }
        let loc = r.read_at(eocd_file_off - 20, 20)?;
        if u32_at(&loc, 0) != SIG_EOCD64_LOCATOR {
            return Err(format!(
                "zip {}: ZIP64 locator missing (this archive needs ZIP64 support)",
                r.path.display()
            ));
        }
        let z64_off = u64_at(&loc, 8);
        if z64_off + 56 > r.size {
            return Err(format!(
                "zip {}: ZIP64 end-of-central-directory offset {z64_off} is out of range",
                r.path.display()
            ));
        }
        let z = r.read_at(z64_off, 56)?;
        if u32_at(&z, 0) != SIG_EOCD64 {
            return Err(format!(
                "zip {}: bad ZIP64 end-of-central-directory signature",
                r.path.display()
            ));
        }
        entries = u64_at(&z, 32);
        cd_size = u64_at(&z, 40);
        cd_off = u64_at(&z, 48);
    }

    if cd_size > MAX_CD {
        return Err(format!(
            "zip {}: central directory of {cd_size} bytes is implausibly large",
            r.path.display()
        ));
    }
    if cd_off + cd_size > r.size {
        return Err(format!(
            "zip {}: central directory at {cd_off}+{cd_size} is past end of file ({} bytes)",
            r.path.display(),
            r.size
        ));
    }
    Ok(Eocd { entries, cd_off, cd_size })
}

// ---------------------------------------------------------------------------
// Central directory entries
