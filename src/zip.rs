    #[test]
    fn real_lwjgl_jar_extracts_the_native() {
        // Optional cross-check against a real download, skipped when absent.
        let jar = std::env::temp_dir().join("lfl-lwjgl-3.3.1-natives-windows.jar");
        if !jar.exists() {
            return;
        }
        let names = list(&jar).expect("list real jar");
        assert!(names.iter().any(|n| n.ends_with("org/lwjgl/lwjgl.dll")));
        let t = TempDir::new("real");
        let out = t.path().join("natives");
        let n = extract(&jar, &out, &[]).expect("extract real jar");
        assert!(n >= 1);
        let dll = out.join("lwjgl.dll");
        assert!(dll.exists(), "flat copy must exist for java.library.path");
        let bytes = std::fs::read(&dll).unwrap();
        assert_eq!(&bytes[..2], b"MZ");
        assert!(bytes.len() > 100_000);
        assert!(!out.join("META-INF").exists());
    }
