#[derive(Clone)]
struct Entry {
    name: String,
    method: u16,
    csize: u64,
    usize: u64,
    local_off: u64,
    flags: u16,
}

impl Entry {
    /// A directory entry ends with `/` or `\` (and usually has size 0).
    fn is_dir(&self) -> bool {
        self.name.ends_with('/') || self.name.ends_with('\\')
    }
}

/// CP437 high half (0x80..=0xFF). Names are UTF-8 when general-purpose bit 11
/// is set; everything else (old jars, LWJGL 2 natives) is CP437.
const CP437_HIGH: &str = "ÇüéâäàåçêëèïîìÄÅÉæÆôöòûùÿÖÜ¢£¥₧ƒáíóúñÑªº¿⌐¬½¼¡«»░▒▓│┤╡╢╖╕╣║╗╝╜╛┐└┴┬├─┼╞╟╚╔╩╦╠═╬╧╨╤╥╙╘╒╓╫╪┘┌█▄▌▐▀αßΓπΣσµτΦΘΩδ∞φε∩≡±≥≤⌠⌡÷≈°∙·√ⁿ²■\u{a0}";

fn decode_name(raw: &[u8], utf8: bool) -> String {
    match std::str::from_utf8(raw) {
        Ok(s) if utf8 => s.to_string(),
        // Even flagged non-UTF-8 names are often valid UTF-8 in practice.
        Ok(s) => s.to_string(),
        Err(_) => {
            let mut out = String::with_capacity(raw.len());
            for &b in raw {
                if b < 0x80 {
                    out.push(b as char);
                } else {
                    match CP437_HIGH.chars().nth((b - 0x80) as usize) {
                        Some(c) => out.push(c),
                        None => out.push('?'),
                    }
                }
            }
            out
        }
    }
}

fn read_entries(r: &mut Reader, eocd: &Eocd) -> Res<Vec<Entry>> {
    let cd = if eocd.cd_size == 0 {
        Vec::new()
    } else {
        r.read_at(eocd.cd_off, eocd.cd_size as usize)?
    };
    let mut out = Vec::with_capacity(eocd.entries.min(4096) as usize);
    let mut p = 0usize;
    while p + 46 <= cd.len() {
        if u32_at(&cd, p) != SIG_CENTRAL {
            return Err(format!(
                "zip {}: bad central directory signature at offset {}",
                r.path.display(),
                eocd.cd_off + p as u64
            ));
        }
        let flags = u16_at(&cd, p + 8);
        let method = u16_at(&cd, p + 10);
        let mut csize = u32_at(&cd, p + 20) as u64;
        let mut usize_ = u32_at(&cd, p + 24) as u64;
        let name_len = u16_at(&cd, p + 28) as usize;
        let extra_len = u16_at(&cd, p + 30) as usize;
        let comment_len = u16_at(&cd, p + 32) as usize;
        let mut local_off = u32_at(&cd, p + 42) as u64;

        let name_start = p + 46;
        let extra_start = name_start + name_len;
        let next = extra_start + extra_len + comment_len;
        if next > cd.len() {
            return Err(format!(
                "zip {}: truncated central directory entry at offset {}",
                r.path.display(),
                eocd.cd_off + p as u64
            ));
        }
        let name = decode_name(&cd[name_start..extra_start], flags & 0x0800 != 0);

        // ZIP64 extended information: values appear only for fields that
        // overflowed, in the fixed order usize, csize, local_off.
        if usize_ == 0xFFFF_FFFF || csize == 0xFFFF_FFFF || local_off == 0xFFFF_FFFF {
            let mut q = extra_start;
            while q + 4 <= extra_start + extra_len {
                let id = u16_at(&cd, q);
                let len = u16_at(&cd, q + 2) as usize;
                let body = q + 4;
                if body + len > extra_start + extra_len {
                    break;
                }
                if id == EXTRA_ZIP64 {
                    let mut k = body;
                    if usize_ == 0xFFFF_FFFF && k + 8 <= body + len {
                        usize_ = u64_at(&cd, k);
                        k += 8;
                    }
                    if csize == 0xFFFF_FFFF && k + 8 <= body + len {
                        csize = u64_at(&cd, k);
                        k += 8;
                    }
                    if local_off == 0xFFFF_FFFF && k + 8 <= body + len {
                        local_off = u64_at(&cd, k);
                    }
                    break;
                }
                q = body + len;
            }
        }

        out.push(Entry { name, method, csize, usize: usize_, local_off, flags });
        p = next;
    }
    Ok(out)
}

fn entries_of(zip: &Path) -> Res<(Reader, Vec<Entry>)> {
    let mut r = Reader::open(zip)?;
    let eocd = find_eocd(&mut r)?;
    let entries = read_entries(&mut r, &eocd)?;
    Ok((r, entries))
}

/// All entry names, in central-directory order, exactly as stored (directory
/// entries keep their trailing `/`).
pub fn list(zip: &Path) -> Res<Vec<String>> {
    let (_r, entries) = entries_of(zip)?;
    Ok(entries.into_iter().map(|e| e.name).collect())
}

/// Read one entry into memory as text, without extracting the whole archive.
///
/// Used to peek at `fabric.mod.json` and friends: a mod jar can be tens of
/// megabytes, and only a few kilobytes of metadata are needed. `candidates` are
/// tried in order (case-insensitive, `/`-separated) and the first hit wins.
///
/// Refuses entries larger than 4 MiB so a malformed archive cannot make this
/// allocate without bound.
pub fn read_entry_string(zip: &Path, candidates: &[&str]) -> Res<String> {
    const LIMIT: u64 = 4 * 1024 * 1024;
    let (mut r, entries) = entries_of(zip)?;
    let want: Vec<String> = candidates
        .iter()
        .map(|c| c.replace('\\', "/").to_ascii_lowercase())
        .collect();
    let entry = entries
        .iter()
        .find(|e| {
            !e.is_dir() && want.iter().any(|w| e.name.replace('\\', "/").to_ascii_lowercase() == *w)
        })
        .ok_or_else(|| format!("zip {}: none of {:?} present", zip.display(), candidates))?;
    if entry.usize > LIMIT {
        return Err(format!(
            "zip {}: entry {} is {} bytes, refusing to read it entirely",
            zip.display(),
            entry.name,
            entry.usize
        ));
    }
    if entry.name.contains('/') == false && entry.name.is_empty() {
        return Err(format!("zip {}: empty entry name", zip.display()));
    }
    let data_off = data_offset(&mut r, entry)?;
    let bytes = match entry.method {
        0 => r.read_at(data_off, entry.csize as usize)?,
        8 => {
            let comp = r.read_at(data_off, entry.csize as usize)?;
            crate::inflate::inflate_raw(&comp, entry.usize as usize)
                .map_err(|e| format!("zip {}: entry {}: {e}", zip.display(), entry.name))?
        }
        m => {
            return Err(format!(
                "zip {}: entry {} uses unsupported compression method {m}",
                zip.display(),
                entry.name
            ))
        }
    };
    Ok(String::from_utf8_lossy(&bytes).to_string())
}

/// Byte offset of an entry's payload (local header length + its name/extra).
fn data_offset(r: &mut Reader, e: &Entry) -> Res<u64> {
    let local = r.read_at(e.local_off, 30)?;
    if local.len() < 30 || u32::from_le_bytes([local[0], local[1], local[2], local[3]]) != 0x0403_4b50
    {
        return Err(format!(
            "zip {}: bad local header for {}",
            r.path.display(),
            e.name
        ));
    }
    let name_len = u16::from_le_bytes([local[26], local[27]]) as u64;
    let extra_len = u16::from_le_bytes([local[28], local[29]]) as u64;
    Ok(e.local_off + 30 + name_len + extra_len)
}

// ---------------------------------------------------------------------------
// Extraction helpers
// ---------------------------------------------------------------------------

/// Normalise an entry name to a relative path, or reject it.
///
/// Rejected: empty names, absolute paths (`/x`, `C:\x`, `\\server\share`),
/// and any `..` component. Returns `/`-separated components.
fn safe_components(name: &str) -> Option<Vec<String>> {
    let s = name.replace('\\', "/");
    if s.is_empty() || s.starts_with('/') {
        return None;
    }
    let bytes = s.as_bytes();
    if bytes.len() >= 2 && bytes[0].is_ascii_alphabetic() && bytes[1] == b':' {
        return None;
    }
    let mut parts = Vec::new();
    for part in s.split('/') {
        match part {
            "" | "." => continue, // tolerate `//` and `./`
            ".." => return None,
            p => parts.push(p.to_string()),
        }
    }
    if parts.is_empty() {
        return None;
    }
    Some(parts)
}

fn is_meta_inf(name: &str) -> bool {
    let upper: String = name.chars().take(9).flat_map(|c| c.to_uppercase()).collect();
    upper.starts_with("META-INF/") || upper.starts_with("META-INF\\")
}

fn excluded(name: &str, excludes: &[&str]) -> bool {
    excludes.iter().any(|f| !f.is_empty() && name.contains(f))
}

/// Names that get a flat copy so `java.library.path` finds them.
fn is_native(name: &str) -> bool {
    let lower = name.to_ascii_lowercase();
    lower.ends_with(".dll") || lower.ends_with(".exe")
}

fn write_file(dest: &Path, data: &[u8]) -> Res<()> {
    if let Some(parent) = dest.parent() {
        mkdirs(parent)?;
    }
    let mut f = File::create(dest).map_err(|e| format!("cannot create {}: {e}", dest.display()))?;
    f.write_all(data)
        .map_err(|e| format!("cannot write {}: {e}", dest.display()))?;
    Ok(())
}

/// Copy `len` compressed bytes from the archive to `dest`. `stored` copies them
/// byte for byte (method 0); `deflate` inflates into memory first (method 8).
fn materialize(
    r: &mut Reader,
    data_off: u64,
    len: u64,
    method: u16,
    usize_: u64,
    dest: &Path,
) -> Res<()> {
    if len == 0 {
        return write_file(dest, &[]);
    }
    if let Some(parent) = dest.parent() {
        mkdirs(parent)?;
    }
    match method {
        0 => {
            let mut out =
                File::create(dest).map_err(|e| format!("cannot create {}: {e}", dest.display()))?;
            let mut buf = vec![0u8; 64 * 1024];
            let mut done = 0u64;
            while done < len {
                let want = (len - done).min(buf.len() as u64) as usize;
                r.read_into(data_off + done, &mut buf[..want])?;
                out.write_all(&buf[..want])
                    .map_err(|e| format!("cannot write {}: {e}", dest.display()))?;
                done += want as u64;
            }
            Ok(())
        }
        8 => {
            let comp = r.read_at(data_off, len as usize)?;
            let data = inflate::inflate_raw(&comp, usize_ as usize).map_err(|e| {
                format!("zip {}: entry {}: {e}", r.path.display(), dest.display())
            })?;
            write_file(dest, &data)
        }
        m => Err(format!(
            "zip {}: unsupported compression method {m}",
            r.path.display()
        )),
    }
}

/// Extract a zip into `out_dir`.
///
/// Skips directories, `META-INF/*`, entries containing an `excludes` fragment,
/// entries escaping `out_dir`, and entries using an unsupported or encrypted
/// method (those are reported through [`info`] rather than aborting).
/// Every `.dll`/`.exe` living under a directory is additionally written flat
/// into `out_dir` so the JVM's `java.library.path` lookup finds it.
///
/// Returns the number of distinct files written.
pub fn extract(zip: &Path, out_dir: &Path, excludes: &[&str]) -> Res<usize> {
    let (mut r, entries) = entries_of(zip)?;
    mkdirs(out_dir)?;
    let mut written: HashSet<PathBuf> = HashSet::new();

    for e in &entries {
        if e.is_dir() {
            continue;
        }
        if is_meta_inf(&e.name) || excluded(&e.name, excludes) {
            continue;
        }
        if e.flags & 0x0001 != 0 {
            info(&format!("zip: skipping encrypted entry {}", e.name));
            continue;
        }
        let parts = match safe_components(&e.name) {
            Some(p) => p,
            None => {
                info(&format!("zip: skipping unsafe entry name {}", e.name));
                continue;
            }
        };
        if e.usize > MAX_ENTRY {
            info(&format!("zip: skipping oversized entry {} ({} bytes)", e.name, e.usize));
            continue;
        }

        // The local header carries its own name/extra lengths; the central
        // record's sizes are authoritative for the data length.
        if e.local_off + 30 > r.size {
            info(&format!("zip: skipping entry {} with bad local header offset", e.name));
            continue;
        }
        let lh = r.read_at(e.local_off, 30)?;
        if u32_at(&lh, 0) != SIG_LOCAL {
            info(&format!("zip: skipping entry {} with bad local header signature", e.name));
            continue;
        }
        let lname = u16_at(&lh, 26) as u64;
        let lextra = u16_at(&lh, 28) as u64;
        let data_off = e.local_off + 30 + lname + lextra;
        if data_off + e.csize > r.size {
            info(&format!("zip: skipping entry {} (data past end of file)", e.name));
            continue;
        }

        let mut dest = out_dir.to_path_buf();
        for p in &parts {
            dest.push(p);
        }
        if written.contains(&dest) {
            continue;
        }
        match materialize(&mut r, data_off, e.csize, e.method, e.usize, &dest) {
            Ok(()) => {
                written.insert(dest.clone());
            }
            Err(err) => {
                if e.method != 0 && e.method != 8 {
                    info(&format!("zip: skipping {}: {err}", e.name));
                    continue;
                }
                return Err(err);
            }
        }

        // Flat copy for the natives directory (basename only, no directories).
        if parts.len() > 1 && is_native(&parts[parts.len() - 1]) {
            let flat = out_dir.join(parts[parts.len() - 1].as_str());
            if !written.contains(&flat) {
                match materialize(&mut r, data_off, e.csize, e.method, e.usize, &flat) {
                    Ok(()) => {
                        written.insert(flat);
                    }
                    Err(err) => return Err(err),
                }
            }
        }
    }
    Ok(written.len())
}

