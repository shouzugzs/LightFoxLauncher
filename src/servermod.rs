//! Dedicated-server support: download the server jar and generate a working
//! set of first-run config files.
//!
//! This module owns the *server* half of hosting; `hosting.rs` stays about
//! process/tunnel plumbing and never touches Mojang metadata. All file writes
//! are atomic (tmp + rename) like `settings.rs`, so a crash mid-write cannot
//! leave a half-generated server directory behind.
//!
//! OWNER: lead.

use std::path::{Path, PathBuf};

use crate::json::Json;
use crate::util::{mkdirs, Res};

// ---------------------------------------------------------------------------
// 1. Server jar download
// ---------------------------------------------------------------------------

/// Download the vanilla server jar for the version described by
/// `version_json_url` into `dest_dir/server.jar` and return the jar path.
///
/// `version_json_url` is the per-version JSON URL the caller took from the
/// version manifest (`version.rs` lists them); it is fetched with `net::get`
/// and the `downloads.server` entry inside it gives the jar URL, sha1 and
/// size. `net::download` verifies the sha1 while streaming, so a corrupted or
/// tampered jar never lands under the name `server.jar`.
pub fn server_download(version_json_url: &str, dest_dir: &Path) -> Res<PathBuf> {
    let bytes = crate::net::get(version_json_url)
        .map_err(|e| format!("server: cannot fetch version JSON from {version_json_url}: {e}"))?;
    let text = String::from_utf8_lossy(&bytes).into_owned();
    let root = Json::parse(&text).map_err(|e| format!("server: bad version JSON: {e}"))?;

    let url = root
        .path(&["downloads", "server"])
        .and_then(|s| s.str_at("url"))
        .filter(|u| !u.is_empty())
        .ok_or_else(|| {
            format!(
                "server: version JSON from {version_json_url} has no downloads.server.url \
                 (this version may not publish a dedicated server)"
            )
        })?;
    let sha1 = root
        .path(&["downloads", "server"])
        .and_then(|s| s.str_at("sha1"))
        .unwrap_or("")
        .to_string();
    let size = root
        .path(&["downloads", "server"])
        .and_then(|s| s.u64_at("size"))
        .unwrap_or(0);

    mkdirs(dest_dir)?;
    let jar = dest_dir.join("server.jar");
    crate::net::download(url, &jar, &sha1, size)
        .map_err(|e| format!("server: cannot download server jar: {e}"))?;
    Ok(jar)
}

// ---------------------------------------------------------------------------
// 2. Config generation
// ---------------------------------------------------------------------------

/// The exact `eula.txt` content written by [`write_configs`].
///
/// Writing `eula=true` on the user's behalf means **the user accepts the
/// Minecraft EULA** (<https://aka.ms/MinecraftEULA>). The launcher only writes
/// the file so the first start does not abort; the EULA obligation is entirely
/// the server owner's, and the caller should surface that to the user before
/// invoking [`write_configs`].
pub const EULA_BODY: &str = "# Generated by LightFoxLauncher\neula=true\n";

/// Generate `eula.txt`, `server.properties` and `whitelist.json` in `dir`.
///
/// - `eula.txt`: `eula=true` — this stands for the user *accepting the
///   Minecraft EULA*; the launcher merely writes the file so the server
///   starts, and the EULA obligation rests with the user, not the launcher.
/// - `server.properties`: minimal offline-mode-friendly set (see below).
/// - `whitelist.json`: `[{"uuid":"...","name":"..."}]` entries with the
///   offline-mode UUID of each name (`hash::offline_uuid`), matching what the
///   server itself computes in `online-mode=false`.
///
/// All three files are written atomically (tmp + rename, the `settings.rs`
/// style) and `dir` is created when missing.
pub fn write_configs(dir: &Path, port: u16, motd: &str, whitelist: &[String]) -> Res<()> {
    mkdirs(dir)?;

    write_atomic(&dir.join("eula.txt"), EULA_BODY)?;

    // `online-mode=false` and `enforce-secure-profile=false` are *required*
    // here: an offline launcher cannot hand the server Mojang-signed session
    // tokens or profile signatures, so the server must not try to verify them.
    // `server-ip=` is deliberately empty — the default "listen on all
    // interfaces" behaviour, which is what port-forwarding/tunnel setups want.
    let props = format!(
        "# Generated by LightFoxLauncher\n\
         server-port={port}\n\
         motd={motd}\n\
         online-mode=false\n\
         enforce-secure-profile=false\n\
         white-list=true\n\
         enforce-whitelist=true\n\
         server-ip=\n\
         view-distance=10\n\
         max-players=20\n"
    );
    write_atomic(&dir.join("server.properties"), &props)?;

    let mut wl = String::from("[");
    for (i, name) in whitelist.iter().enumerate() {
        if i > 0 {
            wl.push(',');
        }
        let uuid = crate::hash::offline_uuid(name);
        wl.push_str(&format!(
            "{{\"uuid\":\"{}\",\"name\":\"{}\"}}",
            crate::json::escape(&uuid),
            crate::json::escape(name)
        ));
    }
    wl.push_str("]\n");
    write_atomic(&dir.join("whitelist.json"), &wl)?;

    Ok(())
}

/// Atomic file write: `settings.rs` style (write `<target>.tmp`, then rename).
fn write_atomic(target: &Path, body: &str) -> Res<()> {
    let tmp = target.with_extension({
        let mut name = target
            .extension()
            .map(|e| e.to_string_lossy().into_owned())
            .unwrap_or_default();
        name.push_str(".tmp");
        name
    });
    std::fs::write(&tmp, body).map_err(|e| format!("cannot write {}: {e}", tmp.display()))?;
    if target.exists() {
        // Windows rename refuses to clobber, so clear the way first.
        let _ = std::fs::remove_file(target);
    }
    std::fs::rename(&tmp, target)
        .map_err(|e| format!("cannot replace {}: {e}", target.display()))
}

// ---------------------------------------------------------------------------
// 3. Validation
// ---------------------------------------------------------------------------

/// Reject ports that cannot work or are hostile to set up.
///
/// `0` is "OS picks one" and leaves the user guessing where the server went;
/// ports below 1024 are privileged on Unix and generally a mistake — that case
/// is a *warning-class* error advising the Minecraft default `25565`, not a
/// hard capability error (an admin *can* bind them).
pub fn validate_port(port: u16) -> Res<()> {
    if port == 0 {
        return Err("端口不能为 0（0 表示随机分配，无法知道服务器开在哪）".to_string());
    }
    if port < 1024 {
        return Err(format!(
            "端口 {port} 低于 1024 的端口需要管理员权限，建议用 25565"
        ));
    }
    Ok(())
}

/// Reject a MOTD the server would mangle or misinterpret.
///
/// The limit is **59 characters** (not bytes — the properties file stores
/// UTF-8, but the vanilla server truncates the *displayed* MOTD around 59
/// characters, so counting `chars()` is what matches the in-game result).
/// Control characters (newlines, tabs, escapes) are rejected because they
/// would either forge extra lines in `server.properties` or render as
/// garbage in the server list.
pub fn validate_motd(motd: &str) -> Res<()> {
    if motd.chars().count() > 59 {
        return Err("MOTD 最多 59 个字符".to_string());
    }
    if motd.chars().any(|c| c.is_control()) {
        return Err("MOTD 不能包含控制字符（换行、制表符等）".to_string());
    }
    Ok(())
}

// ---------------------------------------------------------------- tests

#[cfg(test)]
mod tests {
    use super::*;

    /// Isolated temp dir, `settings.rs` test style; cleaned by the caller.
    fn temp(tag: &str) -> PathBuf {
        let p = std::env::temp_dir().join(format!(
            "lfl-servermod-{}-{}",
            tag,
            std::process::id()
        ));
        let _ = std::fs::remove_dir_all(&p);
        std::fs::create_dir_all(&p).unwrap();
        p
    }

    /// Minimal `key=value` reader for the server.properties round-trip.
    /// Skips comments and blank lines, exactly like the game does.
    fn read_props(path: &Path) -> Vec<(String, String)> {
        std::fs::read_to_string(path)
            .unwrap()
            .lines()
            .filter_map(|l| {
                let l = l.trim();
                if l.is_empty() || l.starts_with('#') {
                    return None;
                }
                l.split_once('=').map(|(k, v)| (k.to_string(), v.to_string()))
            })
            .collect()
    }

    #[test]
    fn server_properties_round_trips() {
        let dir = temp("props");
        write_configs(&dir, 25565, "A LightFox server", &[]).unwrap();
        let got = read_props(&dir.join("server.properties"));
        let want = [
            ("server-port", "25565"),
            ("motd", "A LightFox server"),
            ("online-mode", "false"),
            ("enforce-secure-profile", "false"),
            ("white-list", "true"),
            ("enforce-whitelist", "true"),
            ("server-ip", ""),
            ("view-distance", "10"),
            ("max-players", "20"),
        ];
        for (k, v) in want {
            let hit = got.iter().find(|(gk, _)| gk == k);
            assert_eq!(hit.map(|(_, gv)| gv.as_str()), Some(v), "key {k}");
        }
        assert_eq!(got.len(), want.len(), "no stray keys");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn eula_file_content_is_exact() {
        // Byte-exact: a missing newline or a different comment would still
        // work, but the contract says these are the generated bytes and any
        // regression here is visible to the user who opens the file.
        let dir = temp("eula");
        write_configs(&dir, 25565, "x", &[]).unwrap();
        let body = std::fs::read_to_string(dir.join("eula.txt")).unwrap();
        assert_eq!(body, "# Generated by LightFoxLauncher\neula=true\n");
        assert_eq!(EULA_BODY, body);
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn whitelist_is_valid_json_with_offline_uuids() {
        let names = vec!["Notch".to_string(), "Steve".to_string(), "灰太狼".to_string()];
        let dir = temp("wl");
        write_configs(&dir, 25565, "x", &names).unwrap();
        let text = std::fs::read_to_string(dir.join("whitelist.json")).unwrap();
        let parsed = Json::parse(&text).expect("whitelist.json must be valid JSON");
        let arr = parsed.as_arr().expect("must be a JSON array");
        assert_eq!(arr.len(), 3);
        for (entry, name) in arr.iter().zip(&names) {
            assert_eq!(entry.str_at("name"), Some(name.as_str()));
            assert_eq!(
                entry.str_at("uuid"),
                Some(crate::hash::offline_uuid(name).as_str())
            );
        }
        // Empty whitelist must still be a valid (empty) array, not nothing.
        let dir2 = temp("wl-empty");
        write_configs(&dir2, 25565, "x", &[]).unwrap();
        let empty = Json::parse(
            &std::fs::read_to_string(dir2.join("whitelist.json")).unwrap(),
        )
        .unwrap();
        assert_eq!(empty.as_arr().unwrap().len(), 0);
        let _ = std::fs::remove_dir_all(&dir);
        let _ = std::fs::remove_dir_all(&dir2);
    }

    #[test]
    fn motd_and_names_reach_their_files_verbatim() {
        // UTF-8 (non-ASCII MOTD / names) must survive without mangling.
        let dir = temp("utf8");
        write_configs(&dir, 30000, "生存服 §a在线", &["玩家一".to_string()]).unwrap();
        let got = read_props(&dir.join("server.properties"));
        assert_eq!(
            got.iter().find(|(k, _)| k == "motd").map(|(_, v)| v.as_str()),
            Some("生存服 §a在线")
        );
        let wl = Json::parse(&std::fs::read_to_string(dir.join("whitelist.json")).unwrap())
            .unwrap();
        assert_eq!(wl.at(0).unwrap().str_at("name"), Some("玩家一"));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn write_configs_creates_missing_dir_and_is_idempotent() {
        let dir = temp("mkdirs").join("deeper").join("nested");
        write_configs(&dir, 25565, "x", &[]).unwrap();
        assert!(dir.join("server.properties").is_file());
        assert!(dir.join("eula.txt").is_file());
        assert!(dir.join("whitelist.json").is_file());
        // Second call overwrites cleanly (tmp + rename path with a target
        // already present).
        write_configs(&dir, 25566, "y", &["A".to_string()]).unwrap();
        let got = read_props(&dir.join("server.properties"));
        assert_eq!(
            got.iter().find(|(k, _)| k == "server-port").map(|(_, v)| v.as_str()),
            Some("25566")
        );
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn no_tmp_files_are_left_behind() {
        let dir = temp("notmp");
        write_configs(&dir, 25565, "x", &["A".to_string()]).unwrap();
        let leftovers: Vec<_> = std::fs::read_dir(&dir)
            .unwrap()
            .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())
            .filter(|n| n.ends_with(".tmp"))
            .collect();
        assert!(leftovers.is_empty(), "leftover tmp files: {leftovers:?}");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn validate_port_boundaries() {
        assert!(validate_port(0).is_err(), "0 must be rejected");
        assert!(validate_port(80).is_err(), "<1024 must be rejected");
        assert!(validate_port(1023).is_err());
        assert!(
            validate_port(80).unwrap_err().contains("25565"),
            "the privileged-port error must advise 25565"
        );
        assert!(validate_port(1024).is_ok());
        assert!(validate_port(25565).is_ok());
        assert!(validate_port(65535).is_ok());
    }

    #[test]
    fn validate_motd_boundaries() {
        assert!(validate_motd("").is_ok());
        assert!(validate_motd(&"a".repeat(59)).is_ok(), "59 chars is the limit");
        assert!(validate_motd(&"a".repeat(60)).is_err(), "60 chars must be rejected");
        // Characters, not bytes: '灰' is 3 bytes in UTF-8, so 59 '灰' is
        // 177 bytes but still 59 characters and must pass.
        assert!(validate_motd(&"灰".repeat(59)).is_ok());
        assert!(validate_motd(&"灰".repeat(60)).is_err());
        // Control characters (including newline injection) are rejected.
        assert!(validate_motd("hello\nworld").is_err());
        assert!(validate_motd("tab\there").is_err());
        assert!(validate_motd("\u{1b}[31mred").is_err());
        assert!(validate_motd("普通文本").is_ok());
    }

    // -- live network tests (opt-in) ----------------------------------------

    /// Live test: fetch a real version JSON from the Mojang manifest and
    /// download the actual server jar (tens of MB). Run explicitly with
    /// `cargo test --release -- --ignored servermod`.
    #[test]
    #[ignore]
    fn live_server_download() {
        let manifest = crate::net::get(
            "https://piston-meta.mojang.com/mc/game/version_manifest_v2.json",
        )
        .expect("fetch manifest");
        let m = Json::parse(&String::from_utf8_lossy(&manifest)).unwrap();
        let url = m
            .arr_at("versions")
            .unwrap()
            .iter()
            .find(|v| v.str_at("id") == Some("1.20.4"))
            .and_then(|v| v.str_at("url"))
            .expect("1.20.4 in manifest");

        let dir = temp("live-download");
        let jar = server_download(url, &dir).expect("server download");
        assert!(jar.is_file());
        // The jar is a zip: its first bytes are the PK magic.
        let head = std::fs::read(&jar).unwrap();
        assert!(head.len() > 1000);
        assert_eq!(&head[..2], b"PK", "server.jar must be a zip");
        let _ = std::fs::remove_dir_all(&dir);
    }

    /// Live test for the clean-error path: a version JSON without a
    /// `downloads.server` entry (e.g. a very old or bogus document).
    #[test]
    #[ignore]
    fn live_server_download_rejects_bad_json() {
        let dir = temp("live-bad");
        let err = server_download(
            "https://piston-meta.mojang.com/mc/game/version_manifest_v2.json",
            &dir,
        )
        .unwrap_err();
        assert!(err.contains("downloads.server"), "unexpected error: {err}");
        let _ = std::fs::remove_dir_all(&dir);
    }
}
