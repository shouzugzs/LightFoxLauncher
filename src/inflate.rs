const FIX_CORRUPT: &[u8] = &[0x05, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]; // 9 BTYPE=10 with empty code-length code

const FIX_TRUNC: &[u8] = &[0xed, 0xc6, 0x59, 0x15, 0x00, 0x20, 0x08, 0x00, 0xb0, 0xac, 0x78, 0x20]; // 12 truncated prefix of FIX_DYN_100K

const FIX_BTYPE3: &[u8] = &[0x07]; // 1 BFINAL=1, BTYPE=11 (reserved)

const FIX_BADDIST: &[u8] = &[0x03, 0x02]; // 2 distance 1 with empty output window

    fn rep_100k() -> Vec<u8> {
        b"abcdefghij".repeat(10_240) // exactly 102_400 bytes, as in the fixture
    }

    fn rnd_8192() -> Vec<u8> {
        let mut out = Vec::with_capacity(8192);
        let mut x: u32 = 12345;
        let alpha = b"abcde fghij\n";
        for _ in 0..8192 {
            x = x.wrapping_mul(1664525).wrapping_add(1013904223);
            out.push(alpha[(x >> 16) as usize % alpha.len()]);
        }
        out
    }

    #[test]
    fn empty_output() {
        let out = inflate_raw(FIX_EMPTY, 0).expect("empty stream");
        assert!(out.is_empty(), "expected no bytes, got {}", out.len());
    }

    #[test]
    fn stored_block_hello() {
        assert_eq!(inflate_raw(FIX_HELLO_STORED, 5).unwrap(), b"hello");
    }

    #[test]
    fn fixed_huffman_100k() {
        let out = inflate_raw(FIX_FIXED_100K, 102_400).unwrap();
        assert_eq!(out.len(), 102_400);
        assert_eq!(out, rep_100k());
    }

    #[test]
    fn dynamic_huffman_100k() {
        let out = inflate_raw(FIX_DYN_100K, 102_400).unwrap();
        assert_eq!(out, rep_100k());
    }

    #[test]
    fn dynamic_huffman_random_bytes() {
        let out = inflate_raw(FIX_RND, 8192).unwrap();
        assert_eq!(out, rnd_8192());
    }

    #[test]
    fn back_reference_crosses_window() {
        // 100 KB from a 10-byte period: exercises long, overlapping copies.
        let out = inflate_raw(FIX_DYN_100K, 102_400).unwrap();
        assert_eq!(&out[..20], b"abcdefghijabcdefghij");
        assert_eq!(out[99_990..], rep_100k()[99_990..]);
        // Distance 10 repeats must all agree with the source pattern.
        for i in 0..out.len() {
            assert_eq!(out[i], b"abcdefghij"[i % 10], "mismatch at {i}");
        }
    }

    #[test]
    fn bomb_guard_rejects_oversized_output() {
        let err = inflate_raw(FIX_BOMB, 1000).expect_err("must refuse 1.25 MiB from a 1 KB hint");
        assert!(err.contains("exceeds expected size"), "unexpected error: {err}");
    }

    #[test]
    fn bomb_guard_allows_output_within_expected() {
        let out = inflate_raw(FIX_BOMB, 1_310_720).unwrap();
        assert_eq!(out.len(), 1_310_720);
        assert!(out.iter().all(|&b| b == b'a'));
    }

    #[test]
    fn reserved_block_type_is_an_error() {
        let err = inflate_raw(FIX_BTYPE3, 10).expect_err("BTYPE=11 must fail");
        assert!(err.contains("invalid block type"), "unexpected error: {err}");
    }

    #[test]
    fn truncated_input_is_an_error() {
        let err = inflate_raw(FIX_TRUNC, 102_400).expect_err("truncated stream must fail");
        assert!(err.contains("inflate:"), "unexpected error: {err}");
    }

    #[test]
    fn corrupt_dynamic_table_is_an_error() {
        let err = inflate_raw(FIX_CORRUPT, 100).expect_err("empty code-length code must fail");
        assert!(err.contains("inflate:"), "unexpected error: {err}");
    }

    #[test]
    fn invalid_distance_is_reported() {
        let err = inflate_raw(FIX_BADDIST, 100).expect_err("distance before output start");
        assert!(err.contains("invalid distance"), "unexpected error: {err}");
    }

    #[test]
    fn zlib_wrapper_roundtrip() {
        assert_eq!(inflate_zlib(FIX_ZLIB, 17).unwrap(), b"hello hello hello");
    }

    #[test]
    fn zlib_detects_bad_adler32() {
        let mut bad = FIX_ZLIB.to_vec();
        let n = bad.len();
        bad[n - 1] ^= 0xff;
        let err = inflate_zlib(&bad, 17).expect_err("corrupt checksum must fail");
        assert!(err.contains("adler32"), "unexpected error: {err}");
    }

    #[test]
    fn zlib_too_short() {
        assert!(inflate_zlib(&[], 0).is_err());
        assert!(inflate_zlib(&[0x78], 0).is_err());
    }

    #[test]
    fn never_panics_on_truncation_anywhere() {
        // Every prefix must either decode or return Err — never panic or hang.
        for cut in 0..FIX_DYN_100K.len() {
            if let Ok(out) = inflate_raw(&FIX_DYN_100K[..cut], 102_400) {
                // A short but valid prefix is acceptable (end-of-block reached).
                assert!(out.len() <= 102_400);
            }
        }
        for cut in 0..FIX_HELLO_STORED.len() {
            let _ = inflate_raw(&FIX_HELLO_STORED[..cut], 5);
        }
    }

    #[test]
    fn never_panics_on_bit_flips() {
        for i in 0..FIX_DYN_100K.len().min(64) {
            let mut v = FIX_DYN_100K.to_vec();
            v[i] ^= 0xa5;
            let _ = inflate_raw(&v, 102_400);
        }
    }

    #[test]
    fn constant_block_only_stream_is_bounded() {
        // 0xFF bytes: BTYPE=11 forever -> must error quickly, not loop.
        let junk = vec![0xffu8; 1024];
        assert!(inflate_raw(&junk, 10).is_err());
    }

    #[test]
    fn zeroes_do_not_decode_as_valid_output() {
        let junk = vec![0u8; 64];
        // Either a clean Err or a tiny stored block; must never panic.
        let _ = inflate_raw(&junk, 64);
    }
